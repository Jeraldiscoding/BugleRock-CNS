# ==========================================
# The Slash Command (/ask-buglerock)
# ==========================================
def synthesize_answer(query: str, chunks: list[str]) -> str:
    """Passes the ChromaDB chunks and user's question to Claude."""
    context = "\n\n---\n\n".join(chunks) if chunks else "No relevant meeting context found. Please be polite and let the user know you are ready to answer meeting questions, or just say hello back!"
    prompt = (
        f"You are BungleJungle, an expert AI assistant answering questions based on meeting transcripts.\n"
        f"Use the following transcribed excerpts to answer the user's question. If the user is just saying hello, be polite back.\n\n"
        f"<context>\n{context}\n</context>\n\n"
        f"User Question: {query}"
    )
    
    response = anthropic_client.messages.create(
        model="claude-haiku-4-5-20251001",
        max_tokens=1000,
        messages=[{"role": "user", "content": prompt}]
    )
    
    # Return the text generated by Claude
    return response.content[0].text

@app.command("/ask-bunglejungle")
def handle_ask_buglerock(ack, respond, command):
    """
    Listener for /ask-bunglejungle.
    1. Acknowledges within 3 seconds.
    2. Queries ChromaDB for top 3 chunks.
    3. Synthesizes an answer using Claude.
    4. Responds to the user.
    """
    # Acknowledge the command immediately to prevent Slack timeout
    ack("BungleJungle is reading...")

    user_query = command.get("text", "").strip()
    if not user_query:
        respond("Please provide a question, e.g., `/ask-buglerock What did we discuss with Acme last week?`")
        return

    logger.info(f"Received slack command query: {user_query}")

    try:
        # Get context from Vector Store
        chunks = query_knowledge_base(user_query, n_results=3)
        
        # --- ADDED FOR VISIBILITY: Print out the exact chunks we pulled from ChromaDB! ---
        logger.info(f"==== RETRIEVED {len(chunks)} CHUNKS FROM CHROMADB ====")
        for idx, chunk in enumerate(chunks):
            logger.info(f"Chunk {idx+1}: {chunk}")
        logger.info("======================================================")

        # We don't abort on empty chunks anymore, we let Claude be conversational
        # if there happens to be zero context (e.g. for greetings)

        # Generate answer with Claude
        answer = synthesize_answer(user_query, chunks)
        
        # Send back to standard Slack response
        respond(answer)
        
    except Exception as e:
        logger.error(f"Error processing command: {e}")
        respond("Sorry, I encountered an error while safely retrieving or processing that information.")


