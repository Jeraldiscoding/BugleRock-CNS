def send_draft_for_approval(channel_id: str, draft_text: str):
    """
    Sends a message using Slack's Block Kit formatting including the drafted
    email and interactive buttons to approve or edit the draft.
    """
    blocks = [
        {
            "type": "header",
            "text": {
                "type": "plain_text",
                "text": "📝 New Follow-up Email Draft Generated",
                "emoji": True
            }
        },
        {
            "type": "section",
            "text": {
                "type": "mrkdwn",
                "text": "Please review the drafted email below based on the recent meeting:"
            }
        },
        {
            "type": "section",
            "text": {
                "type": "mrkdwn",
                "text": f"```\n{draft_text}\n```"
            }
        },
        {
            "type": "actions",
            "elements": [
                {
                    "type": "button",
                    "text": {
                        "type": "plain_text",
                        "text": "Approve & Send",
                        "emoji": True
                    },
                    "style": "primary",
                    "value": "approved",
                    "action_id": "approve_draft"
                },
                {
                    "type": "button",
                    "text": {
                        "type": "plain_text",
                        "text": "Edit / Discard",
                        "emoji": True
                    },
                    "style": "danger",
                    "value": "edit_discard",
                    "action_id": "edit_draft"
                }
            ]
        }
    ]
    
    # Notice we're utilizing the initialized `app` token here globally
    app.client.chat_postMessage(
        channel=channel_id,
        text="New follow-up email draft requires your review.",
        blocks=blocks
    )


